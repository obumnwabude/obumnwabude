/**
 * The site only uses PrimeVue's Menu and Sidebar, but the Aura theme CSS styles every
 * PrimeVue component (~316 KB, render-blocking). This keeps only the rules those two
 * components (plus ripple and overlays) need, the theme variables and the Inter font.
 *
 * Re-run after upgrading PrimeVue:  node scripts/subset-primevue-css.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const themeDir = 'node_modules/primevue/resources/themes/aura-light-green';
const source = path.join(root, themeDir, 'theme.css');
const target = path.join(root, 'src/assets/primevue-subset.css');

/** A rule is kept only if every PrimeVue class in its selector belongs to one of these families. */
const KEEP = [
  /^p-menu(-.+)?$/,
  /^p-menuitem(-.+)?$/,
  /^p-submenu-(header|label)$/,
  /^p-sidebar(-.+)?$/,
  /^p-component(-overlay(-.+)?)?$/,
  /^p-connected-overlay(-.+)?$/,
  /^p-ripple(-disabled)?$/,
  /^p-ink(-active)?$/,
  /^p-link$/,
  /^p-hidden(-.+)?$/,
  /^p-icon(-.+)?$/,
  /^p-disabled$/,
  /^p-focus$/,
  /^p-highlight$/,
  /^p-unselectable-text$/,
  /^p-sr-only$/,
];

function keepSelector(selector) {
  if (selector === ':root') return true;
  const classes = [...selector.matchAll(/\.(p-[a-z0-9-]+)/g)].map((match) => match[1]);
  return classes.length > 0 && classes.every((name) => KEEP.some((pattern) => pattern.test(name)));
}

const css = fs.readFileSync(source, 'utf8');
const result = postcss.parse(css);
const usedKeyframes = new Set();

result.walkRules((rule) => {
  if (rule.parent?.type === 'atrule' && /keyframes/.test(rule.parent.name)) return;
  const kept = rule.selectors.filter(keepSelector);
  if (!kept.length) {
    rule.remove();
    return;
  }
  rule.selectors = kept;
  rule.walkDecls(/^animation(-name)?$/, (decl) => decl.value.split(/[\s,]+/).forEach((word) => usedKeyframes.add(word)));
});

result.walkAtRules((atRule) => {
  if (/keyframes$/.test(atRule.name) && !usedKeyframes.has(atRule.params)) atRule.remove();
  else if (atRule.name === 'font-face') {
    atRule.walkDecls('src', (decl) => {
      decl.value = decl.value.replace(/url\("\.\/fonts\//g, `url("../../${themeDir}/fonts/`);
    });
  } else if (atRule.name === 'media' && !atRule.nodes?.length) atRule.remove();
});
result.walkAtRules('media', (atRule) => {
  if (!atRule.nodes?.length) atRule.remove();
});

const header = '/* Generated by scripts/subset-primevue-css.mjs from PrimeVue Aura (light green). Do not edit by hand. */\n';
fs.writeFileSync(target, header + result.toString());
console.log(`PrimeVue CSS: ${(css.length / 1024).toFixed(0)} KB -> ${(fs.statSync(target).size / 1024).toFixed(0)} KB (${path.relative(root, target)})`);
